export function translate(language: Language, key: string, values?: Record<string, string | number>) {
  const dictionary = translations[language] ?? translations[DEFAULT_LANGUAGE];
  let value = dictionary[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;

  if (values) {
    for (const [name, replacement] of Object.entries(values)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }

  return value;
}

export function isLanguage(value: string | null | undefined): value is Language {
  return Boolean(value && LANGUAGES.includes(value as Language));
}
